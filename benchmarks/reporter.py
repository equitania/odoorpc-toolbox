"""Markdown report generator for benchmark results.

Writes comparison tables to benchmark_results/ showing RPC call
reductions between v0.5.1 (baseline) and v0.6.0 (optimized).
"""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

from .rpc_counter import RPCMetrics


def generate_report(
    results: list[tuple[RPCMetrics, RPCMetrics]],
    cache_results: list[RPCMetrics] | None = None,
    output_dir: str | None = None,
) -> str:
    """Generate a Markdown benchmark report.

    Args:
        results: List of (baseline_metrics, optimized_metrics) tuples.
        cache_results: Optional list of cache-specific metrics.
        output_dir: Directory for the report file (default: benchmark_results/).

    Returns:
        Path to the generated report file.
    """
    if output_dir is None:
        output_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "benchmark_results")

    Path(output_dir).mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    report_path = os.path.join(output_dir, f"benchmark_{timestamp}.md")

    lines: list[str] = []
    lines.append(f"# Benchmark Report - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append("")
    lines.append("## RPC Call Comparison: v0.5.1 (Baseline) vs v0.6.0 (Optimized)")
    lines.append("")

    # RPC comparison table
    lines.append("| Scenario | v0.5.1 RPCs | v0.6.0 RPCs | Reduction | v0.5.1 Time (ms) | v0.6.0 Time (ms) | Speedup |")
    lines.append("|----------|-------------|-------------|-----------|------------------|------------------|---------|")

    for baseline, optimized in results:
        reduction = 0.0
        if baseline.rpc_calls > 0:
            reduction = ((baseline.rpc_calls - optimized.rpc_calls) / baseline.rpc_calls) * 100

        speedup = 0.0
        if optimized.total_time_ms > 0:
            speedup = baseline.total_time_ms / optimized.total_time_ms

        lines.append(
            f"| {baseline.scenario} "
            f"| {baseline.rpc_calls} "
            f"| {optimized.rpc_calls} "
            f"| {reduction:.0f}% "
            f"| {baseline.total_time_ms:.1f} "
            f"| {optimized.total_time_ms:.1f} "
            f"| {speedup:.2f}x |"
        )

    # Cache performance table
    if cache_results:
        lines.append("")
        lines.append("## Cache Performance")
        lines.append("")
        lines.append("| Scenario | RPC Calls | Cache Hits | Cache Misses | Hit Rate | Total Time (ms) |")
        lines.append("|----------|-----------|------------|--------------|----------|-----------------|")

        for m in cache_results:
            lines.append(
                f"| {m.scenario} "
                f"| {m.rpc_calls} "
                f"| {m.cache_hits} "
                f"| {m.cache_misses} "
                f"| {m.cache_hit_rate:.0f}% "
                f"| {m.total_time_ms:.1f} |"
            )

    # Method breakdown
    lines.append("")
    lines.append("## RPC Method Breakdown (v0.6.0)")
    lines.append("")

    for _, optimized in results:
        if optimized.rpc_calls_by_method:
            lines.append(f"### {optimized.scenario}")
            lines.append("")
            for method, count in sorted(optimized.rpc_calls_by_method.items()):
                lines.append(f"- `{method}`: {count} call(s)")
            lines.append("")

    lines.append("---")
    lines.append(f"*Generated by odoorpc-toolbox benchmark suite on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*")
    lines.append("")

    report_content = "\n".join(lines)
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(report_content)

    return report_path
